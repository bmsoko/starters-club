// Records every spoken text of the site to audio/<key>.mp3 using macOS voices.
// Run after changing questions:   node tools/make-audio.mjs
// Needs macOS `say` and `ffmpeg`. Writes data/audio-index.js (list of keys).
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync, mkdtempSync } from 'node:fs'
import { execFileSync, execFile } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { tmpdir, cpus } from 'node:os'
import { join } from 'node:path'
import vm from 'node:vm'

const root = fileURLToPath(new URL('..', import.meta.url))
for (const f of ['js/core.js', 'data/listening.js', 'data/unit4.js', 'data/spelling.js', 'data/speaking.js', 'data/vocab.js']) {
  vm.runInThisContext(readFileSync(root + f, 'utf8'), { filename: f })
}
const SC = globalThis.SC

// Speaker -> macOS voice, speech rate (words/min) and pitch factor.
const VOICES = {
// Rate 135 + a pause between sentences gives ~120 words/min for short items
// and ~95 for stories: slow and clear, for Pre A1 children.
  N: { voice: 'Daniel', rate: 135, pitch: 1 },
  M: { voice: 'Daniel', rate: 135, pitch: 0.9 },
  W: { voice: 'Moira', rate: 135, pitch: 1 },
  B: { voice: 'Daniel', rate: 135, pitch: 1.28 },
  G: { voice: 'Moira', rate: 135, pitch: 1.2 },
}
const SHORT_RATE = 105
const SPELLING = /^([A-Z], )+[A-Z]\.?$/ // "B, E, N."
const RATE = 22050

const run = (cmd, args) => new Promise((ok, fail) => execFile(cmd, args, (e, _o, err) => (e ? fail(new Error(err || e.message)) : ok())))

async function record(text, out, tmp) {
  const segs = SC.parseSpeech(text)
  const parts = []
  for (const [i, s] of segs.entries()) {
    const v = VOICES[s.who]
    const aiff = join(tmp, `${i}.aiff`)
    // Spell letters slowly: speak each letter as its own word with pauses.
    const sentences = s.text.split(/(?<=[.?!])\s+/)
    const words = sentences.map((w) => (SPELLING.test(w) ? w.replace(/[.,]/g, '').split(' ').join(' [[slnc 400]] ') : w)).join(' [[slnc 400]] ')
    // A single short sentence needs a lower rate to reach the same ~120 words/min.
    const rate = sentences.length === 1 ? SHORT_RATE : v.rate
    await run('say', ['-v', v.voice, '-r', String(rate), '-o', aiff, words])
    parts.push({ aiff, pitch: v.pitch })
  }
  const args = ['-y', '-loglevel', 'error']
  for (const p of parts) args.push('-i', p.aiff)
  const filters = parts.map((p, i) => {
    const shift = p.pitch === 1 ? '' : `asetrate=${Math.round(RATE * p.pitch)},atempo=${(1 / p.pitch).toFixed(4)},`
    return `[${i}:a]aresample=${RATE},${shift}aresample=${RATE},apad=pad_dur=0.8[a${i}]`
  })
  filters.push(parts.map((_, i) => `[a${i}]`).join('') + `concat=n=${parts.length}:v=0:a=1[out]`)
  args.push('-filter_complex', filters.join(';'), '-map', '[out]', '-ac', '1', '-ar', String(RATE), '-b:a', '48k', out)
  await run('ffmpeg', args)
}

const texts = SC.spokenTexts(globalThis.SC_DATA)
const dir = root + 'audio/'
mkdirSync(dir, { recursive: true })
const keys = texts.map(SC.audioKey)
if (new Set(keys).size !== keys.length) throw new Error('audio key collision')
const force = process.argv.includes('--force')
const todo = texts.filter((t) => force || !existsSync(dir + SC.audioKey(t) + '.mp3'))

let done = 0
const queue = [...todo]
await Promise.all(Array.from({ length: Math.min(6, cpus().length) }, async () => {
  for (let t; (t = queue.shift()) !== undefined;) {
    const tmp = mkdtempSync(join(tmpdir(), 'sc-audio-'))
    try { await record(t, dir + SC.audioKey(t) + '.mp3', tmp) } finally { rmSync(tmp, { recursive: true, force: true }) }
    if (++done % 25 === 0) console.log(`${done}/${todo.length}`)
  }
}))

// Remove files nothing uses any more.
const keep = new Set(keys.map((k) => k + '.mp3'))
let removed = 0
for (const f of readdirSync(dir)) if (f.endsWith('.mp3') && !keep.has(f)) { rmSync(dir + f); removed++ }

writeFileSync(root + 'data/audio-index.js',
  '// Generated by tools/make-audio.mjs: keys of recorded files in audio/. Do not edit.\n' +
  `;(globalThis.SC_DATA = globalThis.SC_DATA || {}).audioIndex = ${JSON.stringify(keys.sort())}\n`)
console.log(`recorded ${todo.length}, removed ${removed}, total ${keys.length}`)
